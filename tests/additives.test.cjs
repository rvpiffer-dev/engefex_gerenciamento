'use strict';
/* Execute com: node tests/additives.test.cjs */
const assert=require('node:assert/strict');
global.window=global;
global.Obras=require('../dist/domain.js');
require('../dist/manager.js');
const A=require('../dist/additives.js');
const P=require('../dist/project-profit.js');
const D=global.Obras,M=global.EngefexManager;
const seed={version:1,dataModel:2,projects:[{id:'p',name:'Obra teste',value:100000}],stages:[],activities:[],issues:[],checklists:[],tasks:[],materials:[],stockMoves:[],costs:[],quotes:[],measurements:[],receipts:[],diary:[],teams:[],history:[],facts:[],documents:[],budgetStages:[],budgetItems:[]};
const r=A.blank(seed,'p');r.amendment.title='Cobertura ampliada';
r.amendment.lines=[{id:'r1',name:'Telha',unit:'m²',quantity:12.345,unitPrice:100.12},{id:'r2',name:'Pingadeira',unit:'m',quantity:5,unitPrice:70}];
let s=A.commit(seed,r,'Rascunho');
assert.equal(s.budgetItems.length,0);assert.equal(D.contractValue(s,'p'),100000);
assert.equal(A.totals(s,'p').pending,1585.98);
s=A.commit(s,r,'Em aprovação');
assert.equal(s.budgetItems.length,0);assert.equal(D.contractValue(s,'p'),100000);
s=A.commit(s,r,'Aprovado');
assert.equal(s.budgetItems.length,2);assert.equal(D.contractValue(s,'p'),101585.98);
assert.equal(D.stats(s,'p').sale,101585.98);assert.equal(P.calculate(s,'p').contract/100,101585.98);
assert.throws(()=>A.commit(s,r,'Aprovado'),/finalizado/);
assert.throws(()=>M.remove(s,'budgetItems',s.budgetItems[0].id),/preservados/);
assert.throws(()=>M.save(s,'budgetStages',{...s.budgetStages[0],name:'alterado'}),/Aditivos/);
const changed=JSON.parse(JSON.stringify(s));changed.budgetItems[0].unitPrice+=100;
assert.throws(()=>D.backupValid(changed),/Itens aprovados/);
const duplicate=A.blank(s,'p');duplicate.amendment.number=r.amendment.number;duplicate.amendment.title='Repetido';
assert.throws(()=>A.commit(s,duplicate,'Rascunho'),/existe um aditivo/);
const second=A.blank(s,'p');second.amendment.title='Recusado';
second.amendment.lines=[{id:'x',name:'Serviço',unit:'un',quantity:1,unitPrice:50}];
const refused=A.commit(s,second,'Recusado');
assert.equal(D.contractValue(refused,'p'),101585.98);
assert.match(A.render(s,'p'),/ADITIVO 001|AD 001/);
const reopen=A.changeFinalized(s,r.id,false);
assert.equal(reopen.budgetItems.length,0);
assert.equal(D.contractValue(reopen,'p'),100000);
assert.equal(reopen.budgetStages.find(x=>x.id===r.id).amendment.status,'Em aprovação');
const removed=A.changeFinalized(s,r.id,true);
assert.equal(removed.budgetStages.some(x=>x.id===r.id),false);
assert.equal(removed.budgetItems.length,0);
assert.equal(D.contractValue(removed,'p'),100000);
const linked=JSON.parse(JSON.stringify(s));linked.measurements.push({id:'m-test',project:'p',activity:s.budgetItems[0].id,quantity:1});
assert.throws(()=>A.changeFinalized(linked,r.id,true),/vínculos/);
assert.throws(()=>A.changeFinalized(linked,r.id,false),/vínculos/);
console.log('Aditivos: verificações aprovadas.');
